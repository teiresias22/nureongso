"""글자 표 파서만 본다. 줄바꿈이 이름 한가운데를 자르는 게 유일하게 어려운 곳이다."""

from districts import clean, parse

TABLE = """
┌─────────┬──────────────────────┐
│선 거 구 명       │선    거    구    역          │
├─────────┴──────────────────────┤
│서울특별시(지역구 : 48)                          │
├─────────┬──────────────────────┤
│종로구선거구      │종로구 일원                   │
│광진구갑선거구    │중곡제1동, 능동, 광장동, 군자 │
│                  │동                            │
│중구성동구을선거구│금호2?3가동, 중구 일원        │
└─────────┴──────────────────────┘
│부산광역시(지역구 : 18)                          │
├─────────┬──────────────────────┤
│춘천시철원군화천군│춘천시 신북읍, 동면,          │
│양구군갑선거구    │화천군 일원                   │
""".splitlines()


def test() -> None:
    d = parse(TABLE)
    assert d[("서울특별시", "종로구")] == "종로구 일원"
    # 줄이 넘어가며 '군자'와 '동'이 갈렸다. 붙여야 '군자동'이 된다.
    assert d[("서울특별시", "광진구갑")] == "중곡제1동, 능동, 광장동, 군자동"
    # 깨진 가운뎃점을 되돌린다.
    assert d[("서울특별시", "중구성동구을")] == "금호2·3가동, 중구 일원"
    # 선거구명 자체가 줄을 넘기면 이어 붙인 뒤에야 '선거구'로 끝난다.
    assert ("부산광역시", "춘천시철원군화천군양구군갑") in d
    assert clean("가동,나동") == "가동, 나동"
    assert len(d) == 4, d.keys()
    print("ok")


if __name__ == "__main__":
    test()
