def test_parse_regular() -> None:
    rows = parse(REGULAR, regular=True)
    assert [(r["org"], r["position"], r["name"]) for r in rows] == [
        ("경기도", "도지사", "김동연"), ("경기도 수원시", "시장", "이재준"), ("경기도교육청", "교육감", "임태희")]
    kim = rows[0]
    assert (kim["total_prev_k"], kim["total_now_k"], kim["page"]) == (3505068, 3798097, 1)
    assert kim["breakdown"] == {"건물": 2553000, "예금": 1452577, "채무": 210000}
    assert kim["refused"] == ["모"]
    assert rows[1]["page"] == 2


